function [qRef,dqRef,ddqRef] = config2pressure_reference_N3( ...
    theta,phi,params,thetaDot,phiDot,thetaDDot,phiDDot)
% Convert three section-angle trajectories to pressure-equivalent references.
% theta: bending-plane direction [3xN] (rad), matching pressure2config(1).
% phi: unwrapped, nonnegative bend magnitude [3xN] (rad), matching
% pressure2config(2) only while phi < pi.
% qRef order: [p12;p13;p22;p23;p32;p33] (Pa). These are shape coordinates,
% not measured chamber pressures or valve commands.
% Supply all four angle-derivative arrays to obtain dqRef and ddqRef.
% Parameters r, K, A must use the same numerical conventions as the model.

assert(nargin==3 || nargin==7, ...
    'Supply theta, phi, params, and optionally all four angle derivatives.');
assert(isnumeric(theta) && isnumeric(phi) && ...
    size(theta,1)==3 && isequal(size(theta),size(phi)) && ...
    all(isfinite(theta(:))) && all(isfinite(phi(:))) && ...
    all(phi(:)>=0) && all(phi(:)<pi), ...
    'theta and phi must be finite 3xN arrays with 0 <= phi < pi.');
assert(isequal(size(params.r),[3,1]) && ...
    isequal(size(params.K),[3,1]) && ...
    isequal(size(params.A),[3,1]) && ...
    all(isfinite(params.r)) && all(isfinite(params.K)) && ...
    all(isfinite(params.A)) && all(params.r>0) && ...
    all(params.K>0) && all(params.A>0));

scale = params.K./(params.A.*params.r);
ct = cos(theta); st = sin(theta);
u = phi.*ct; v = phi.*st;
qRef = packBendingComponents(u,v,scale);
dqRef = []; ddqRef = [];
if nargin==7
    assert(isequal(size(thetaDot),size(theta)) && ...
        isequal(size(phiDot),size(theta)) && ...
        isequal(size(thetaDDot),size(theta)) && ...
        isequal(size(phiDDot),size(theta)) && ...
        all(isfinite(thetaDot(:))) && all(isfinite(phiDot(:))) && ...
        all(isfinite(thetaDDot(:))) && all(isfinite(phiDDot(:))));
    uDot = phiDot.*ct-phi.*st.*thetaDot;
    vDot = phiDot.*st+phi.*ct.*thetaDot;
    uDDot = phiDDot.*ct-2*phiDot.*st.*thetaDot ...
        -phi.*ct.*thetaDot.^2-phi.*st.*thetaDDot;
    vDDot = phiDDot.*st+2*phiDot.*ct.*thetaDot ...
        -phi.*st.*thetaDot.^2+phi.*ct.*thetaDDot;
    dqRef = packBendingComponents(uDot,vDot,scale);
    ddqRef = packBendingComponents(uDDot,vDDot,scale);
end
end

function q = packBendingComponents(u,v,scale)
q = zeros(6,size(u,2));
q(1:2:6,:) = scale.*(u/3-v/sqrt(3));
q(2:2:6,:) = scale.*(u/3+v/sqrt(3));
end
